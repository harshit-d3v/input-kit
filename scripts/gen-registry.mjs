import { readdirSync, readFileSync, writeFileSync, existsSync, statSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const PKGS = 'C:/harshitJet/input-kit/packages';
const OUT = 'C:/harshitJet/input-kit/apps/site/lib';

const walk = (d) => readdirSync(d, { withFileTypes: true }).flatMap((e) =>
  e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]);

const dirs = readdirSync(PKGS).filter((d) => statSync(join(PKGS, d)).isDirectory()).sort();
const entries = [];

for (const slug of dirs) {
  const dir = join(PKGS, slug);
  const pj = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));

  let srcLines = 0, testLines = 0;
  const srcDir = join(dir, 'src');
  if (existsSync(srcDir)) {
    for (const f of walk(srcDir)) {
      if (!/\.(ts|tsx)$/.test(f)) continue;
      const n = readFileSync(f, 'utf8').split('\n').length;
      if (/\.(test|spec)\.(ts|tsx)$/.test(f)) testLines += n; else srcLines += n;
    }
  }

  // Named exports, parsed from the entry file — used to show the real API surface.
  let exportNames = [];
  const entry = ['src/index.tsx', 'src/index.ts'].map((p) => join(dir, p)).find(existsSync);
  if (entry) {
    const body = readFileSync(entry, 'utf8');
    const re = /export\s+(?:declare\s+)?(?:async\s+)?(?:function|const|let|class|interface|type|enum)\s+([A-Za-z_$][\w$]*)/g;
    let m;
    while ((m = re.exec(body))) exportNames.push(m[1]);
    const re2 = /export\s*\{([^}]+)\}/g;
    while ((m = re2.exec(body))) {
      for (const part of m[1].split(',')) {
        const name = part.trim().split(/\s+as\s+/).pop()?.trim();
        if (name && /^[A-Za-z_$][\w$]*$/.test(name)) exportNames.push(name);
      }
    }
    exportNames = [...new Set(exportNames)].filter((n) => n !== 'default');
  }

  const demoPath = join(dir, 'test-demo', 'demo.tsx');
  const hasDemo = existsSync(demoPath);
  const demoLines = hasDemo ? readFileSync(demoPath, 'utf8').split('\n').length : 0;

  entries.push({
    slug,
    name: pj.name,
    version: pj.version,
    description: pj.description || '',
    keywords: pj.keywords || [],
    srcLines,
    testLines,
    hasTests: testLines > 0,
    exportNames,
    hasDemo,
    isStubDemo: hasDemo && demoLines <= 30,
    deps: Object.keys(pj.dependencies || {}),
  });
}

mkdirSync(OUT, { recursive: true });

const ts = `// GENERATED by scripts/gen-registry.mjs — do not edit by hand.
// Run \`npm run gen:registry\` from the repo root after adding or changing a package.

export interface PackageEntry {
  slug: string;
  name: string;
  version: string;
  description: string;
  keywords: string[];
  srcLines: number;
  testLines: number;
  hasTests: boolean;
  exportNames: string[];
  hasDemo: boolean;
  isStubDemo: boolean;
  deps: string[];
}

export const packages: PackageEntry[] = ${JSON.stringify(entries, null, 2)};

/** @input-kit/phone lives in its own repository, so it is listed but not demoed here. */
export const externalPackages = [
  {
    slug: 'phone',
    name: '@input-kit/phone',
    version: '0.3.0',
    description:
      'Headless React phone input with 245 calling regions, libphonenumber-powered formatting and validation',
    repo: 'https://github.com/harshit-d3v/input-kit-phone',
  },
];

export const bySlug = new Map(packages.map((p) => [p.slug, p]));

export const totals = {
  count: ${entries.length},
  srcLines: ${entries.reduce((a, e) => a + e.srcLines, 0)},
  testLines: ${entries.reduce((a, e) => a + e.testLines, 0)},
  tested: ${entries.filter((e) => e.hasTests).length},
};
`;

writeFileSync(join(OUT, 'registry.ts'), ts);
console.log(`registry.ts written: ${entries.length} packages`);
console.log(`stub demos: ${entries.filter((e) => e.isStubDemo).map((e) => e.slug).join(', ')}`);
console.log(`no demo file: ${entries.filter((e) => !e.hasDemo).map((e) => e.slug).join(', ') || 'none'}`);
